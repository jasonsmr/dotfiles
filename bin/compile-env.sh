fizban_write_cross(){
  __resolve_ndk
  mkdir -p "$HOME/.config/meson/cross"
  local dir="$HOME/.config/meson/cross"
  local which="${1:-both}"
  if [ "$which" = "cross" ] || [ "$which" = "both" ]; then
    __cross_body_cross | __expand_cross_vars > "$dir/_current-ndk-cross.ini"
  fi
  if [ "$which" = "hybrid" ] || [ "$which" = "both" ]; then
    __cross_body_hybrid | __expand_cross_vars > "$dir/_current-ndk-hybrid.ini"
  fi
}

# put this helper anywhere in compile-env.sh (e.g., right under fizban_write_cross)
__expand_cross_vars(){
  sed \
    -e "s|@NDK_LLVM_BIN@|$NDK_LLVM_BIN|g" \
    -e "s|@NDK_TRIPLE@|$NDK_TRIPLE|g" \
    -e "s|@NDK_SYSROOT@|$NDK_SYSROOT|g" \
    -e "s|@PREFIX@|$PREFIX|g"
}

fizban_report(){
  cat <<EOF
[compile-env]
  PROFILE       : ${PROFILE:-<unset>}
  ANDROID_API   : ${ANDROID_API:-<unset>}
  ANDROID_HOME  : ${ANDROID_HOME:-<unset>}
  ANDROID_NDK_HOME : ${ANDROID_NDK_HOME:-<unset>}
  TOOLCHAIN     : ${TOOLCHAIN:-<unset>}
  NDK_LLVM_BIN  : ${NDK_LLVM_BIN:-<unset>}
  NDK_SYSROOT   : ${NDK_SYSROOT:-<unset>}
  NDK_TRIPLE    : ${NDK_TRIPLE:-<unset>}
  ENV_MODE      : ${ENV_MODE:-<unset>}
EOF
}

fizban_cc(){ __resolve_ndk; echo "CC : ${NDK_LLVM_BIN:+$NDK_LLVM_BIN/}$NDK_TRIPLE-clang"; echo "CXX: ${NDK_LLVM_BIN:+$NDK_LLVM_BIN/}$NDK_TRIPLE-clang++"; echo "SYSROOT: ${NDK_SYSROOT:-<unset>}"; }

fizban_check(){
  __resolve_ndk
  local clang="${NDK_LLVM_BIN:-}/clang"
  if [ -x "$clang" ]; then
    if file "$clang" | grep -qi 'aarch64'; then echo "[ok] NDK clang is native aarch64: $clang"; else echo "[warn] NDK clang exists but isn't native aarch64: $(file "$clang")"; fi
    "$clang" --version 2>/dev/null | head -n1
  else
    echo "[err] clang not found at: $clang"
  fi
}

__set_mode(){
  case "${1:-hybrid}" in
    cross)  export ENV_MODE="ndk-cross" ;;
    hybrid) export ENV_MODE="ndk-hybrid" ;;
    native) export ENV_MODE="termux-native" ;;
    tools)  export ENV_MODE="sdk-tools" ;;
    *) export ENV_MODE="ndk-hybrid" ;;
  esac
}

fizban_use(){
  # fizban_use android --ndk <ver|latest> --api <N> [--mode cross|hybrid|native|tools] [--persist] [--quiet]
  # fizban_use mingw [--persist] [--quiet]
  local persist=0 quiet="${FIZBAN_QUIET:-0}" sub="${1:-}"; shift || true
  case "$sub" in
    android)
      PROFILE=android
      local mode="hybrid"
      while [ $# -gt 0 ]; do
        case "$1" in
          --ndk)     NDK_VERSION="${2:?}"; shift 2;;
          --api)     ANDROID_API="${2:?}"; shift 2;;
          --mode)    mode="${2:?}"; shift 2;;
          --persist) persist=1; shift;;
          --quiet)   quiet=1; shift;;
          *) echo "usage: fizban_use android --ndk <ver|latest> --api <N> [--mode cross|hybrid|native|tools] [--persist] [--quiet]"; return 1;;
        esac
      done
      __resolve_ndk
      fizban_write_cross both
      __set_mode "$mode"
      [ $persist -eq 1 ] && __cfg_save
      ;;
    mingw)
      PROFILE=mingw
      unset ANDROID_NDK_HOME TOOLCHAIN NDK_LLVM_BIN NDK_SYSROOT NDK_TRIPLE
      export TARGET="aarch64-w64-mingw32"
      export CC="$(command -v clang)"; export CXX="$(command -v clang++)"
      export AR="$(command -v llvm-ar)"; export RANLIB="$(command -v llvm-ranlib)"; export STRIP="$(command -v llvm-strip)"
      __set_mode native
      [ "${1:-}" = "--persist" ] && __cfg_save
      ;;
    *)
      echo "usage: fizban_use {android|mingw} …"; return 1;;
  esac
  [ "$quiet" = "1" ] || fizban_report
}

fizban_load_persisted(){ __cfg_load; : "${PROFILE:=android}"; if [ "$PROFILE" = "android" ]; then __resolve_ndk; fizban_write_cross both; else FIZBAN_QUIET=1 fizban_use mingw; fi; }

if [ "$__as_script" -eq 1 ]; then
  case "${1:-}" in
    use) shift; fizban_use "$@";;
    report) fizban_report;;
    load) fizban_load_persisted;;
    write-cross) shift; fizban_write_cross "${1:-both}";;
    check) fizban_check;;
    cc) fizban_cc;;
    *) cat <<USAGE
usage: $(basename "$0") {use|report|load|write-cross|check|cc} ...
  use android --ndk <ver|latest> --api <N> [--persist]
  use mingw [--persist]
  report
  load
  write-cross [cross|hybrid]
  check
  cc
USAGE
       exit 1;;
  esac
fi

