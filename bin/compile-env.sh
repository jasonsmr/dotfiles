#!/data/data/com.termux/files/usr/bin/bash
# ---- toolchain/termux prelude ----
if [ -z "$__TOOLCHAIN_PRELUDE" ]; then
  __TOOLCHAIN_PRELUDE=1
  : ${TMP:="$HOME$TMP"}; mkdir -p -- "$TMP"
  # minimal PATH glue (keep short, user can extend in ~/.zshrc)
  if [ -d "$HOME/opt/toolchain/aarch64-linux-android/bin" ]; then
    case ":$PATH:" in *":$HOME/opt/toolchain/aarch64-linux-android/bin:"*) ;; 
      *) PATH="$HOME/opt/toolchain/aarch64-linux-android/bin:$PATH";;
    esac
  fi
fi
# ---- end prelude ----

# compile-env.sh — quiet env helper for Fizban/Termux

__as_script=0
if [ "${BASH_SOURCE[0]-}" = "$0" ] || [ "${ZSH_EVAL_CONTEXT:-}" = "toplevel" ]; then __as_script=1; fi
if [ "$__as_script" -eq 1 ]; then set -e; fi

: "${HOME:?}"
: "${PREFIX:=/data/data/com.termux/files/usr}"
CFG="$HOME/.fizban.env"

__cfg_load(){ [ -f "$CFG" ] && . "$CFG"; }
__cfg_save(){
  : "${PROFILE:=android}"; : "${ANDROID_API:=28}"
  cat >"$CFG" <<EOF
# AUTOGENERATED by compile-env.sh
PROFILE=$PROFILE
ANDROID_API=$ANDROID_API
NDK_VERSION=${NDK_VERSION:-}
EOF
}

__same_target(){
  local a="$1" b="$2" ra rb
  ra="$(readlink -f "$a" 2>/dev/null || printf '%s' "$a")"
  rb="$(readlink -f "$b" 2>/dev/null || printf '%s' "$b")"
  [ "$ra" = "$rb" ]
}
__best_numeric_alias_for(){
  local real="$1" sdk_ndk_dir="$2" best="" cand base
  for cand in "$sdk_ndk_dir"/*; do
    [ -e "$cand" ] || continue
    base="$(basename "$cand")"
    case "$base" in
      [0-9]*.*) __same_target "$cand" "$real" && best="$base" ;;
    esac
  done
  printf '%s' "$best"
}

__resolve_ndk(){
  : "${ANDROID_HOME:=$HOME/opt/android-sdk}"
  : "${ANDROID_SDK_ROOT:=$ANDROID_HOME}"

  if [ "${NDK_VERSION:-}" = "latest" ]; then
    local L="$ANDROID_HOME/ndk/latest"
    if [ -e "$L" ]; then
      local canon base
      canon="$(readlink -f "$L" 2>/dev/null || printf '%s' "$L")"
      export ANDROID_NDK_HOME="$canon"
      base="$(basename "$canon")"
      case "$base" in
        [0-9]*.*) NDK_VERSION="$base" ;;
        *)
          if [ -d "$ANDROID_HOME/ndk" ]; then
            local best="" cand b
            for cand in "$ANDROID_HOME/ndk"/*; do
              [ -e "$cand" ] || continue
              b="$(basename "$cand")"
              case "$b" in
                [0-9]*.*)
                  if [ "$(readlink -f "$cand" 2>/dev/null || printf '%s' "$cand")" = "$canon" ]; then
                    best="$b"
                  fi
                  ;;
              esac
            done
            [ -n "$best" ] && NDK_VERSION="$best"
          fi
          ;;
      esac
    fi
  fi

  if [ -z "${ANDROID_NDK_HOME:-}" ] && [ -n "${NDK_VERSION:-}" ] && [ -d "$ANDROID_HOME/ndk/$NDK_VERSION" ]; then
    export ANDROID_NDK_HOME="$ANDROID_HOME/ndk/$NDK_VERSION"
  fi

  if [ -z "${ANDROID_NDK_HOME:-}" ] && [ -d "$ANDROID_HOME/ndk" ]; then
    local v
    v="$(ls -1 "$ANDROID_HOME/ndk" 2>/dev/null | sort -V | tail -n1)"
    [ -n "$v" ] && export ANDROID_NDK_HOME="$ANDROID_HOME/ndk/$v" && { [ -z "${NDK_VERSION:-}" ] && NDK_VERSION="$v"; }
  fi

  if [ -n "${ANDROID_NDK_HOME:-}" ]; then
    local canon2
    canon2="$(readlink -f "$ANDROID_NDK_HOME" 2>/dev/null || printf '%s' "$ANDROID_NDK_HOME")"
    export ANDROID_NDK_HOME="$canon2"
  fi

  local prebuilt_os="linux-aarch64"
  if [ -d "${ANDROID_NDK_HOME:-}/toolchains/llvm/prebuilt/$prebuilt_os" ]; then
    export TOOLCHAIN="$ANDROID_NDK_HOME/toolchains/llvm/prebuilt/$prebuilt_os"
    export NDK_LLVM_BIN="$TOOLCHAIN/bin"
    export NDK_SYSROOT="$TOOLCHAIN/sysroot"
  else
    unset TOOLCHAIN NDK_LLVM_BIN NDK_SYSROOT
  fi

  : "${ANDROID_API:=28}"
  export NDK_TRIPLE="aarch64-linux-android${ANDROID_API}"
}

__cross_body_cross(){ cat <<'EOF'
[binaries]
c = '@NDK_LLVM_BIN@/@NDK_TRIPLE@-clang'
cpp = '@NDK_LLVM_BIN@/@NDK_TRIPLE@-clang++'
ar = '@NDK_LLVM_BIN@/llvm-ar'
ranlib = '@NDK_LLVM_BIN@/llvm-ranlib'
strip = '@NDK_LLVM_BIN@/llvm-strip'
pkg-config = '@PREFIX@/bin/pkg-config'

[properties]
needs_exe_wrapper = true

[built-in options]
c_args = ['--target=@NDK_TRIPLE@','--sysroot=@NDK_SYSROOT@','-O2','-fPIC']
cpp_args = ['--target=@NDK_TRIPLE@','--sysroot=@NDK_SYSROOT@','-O2','-fPIC','-stdlib=libc++','-isystem','@NDK_SYSROOT@/usr/include/c++/v1']
c_link_args = ['--target=@NDK_TRIPLE@','--sysroot=@NDK_SYSROOT@']
cpp_link_args = ['--target=@NDK_TRIPLE@','--sysroot=@NDK_SYSROOT@']

[host_machine]
system = 'android'
cpu_family = 'aarch64'
cpu = 'armv8-a'
endian = 'little'
EOF
}

