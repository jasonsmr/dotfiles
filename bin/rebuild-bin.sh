  -DCMAKE_CXX_COMPILER="$NDK_LLVM_BIN/$NDK_TRIPLE-clang++" \
  -DARM_DYNAREC=ON -DLD80BITS=OFF -DSTATIC_LINKING=OFF -DHAVE_VULKAN=ON \
