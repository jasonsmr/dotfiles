__cfg_load(){ [ -f "$CFG" ] && . "$CFG"; }
__cfg_save(){
  cat >"$CFG" <<EOF
# AUTOGENERATED by compile-env.sh
PROFILE=${PROFILE:-android}
ANDROID_API=${ANDROID_API:-28}
NDK_VERSION=${NDK_VERSION:-}
EOF
  echo "[compile-env] wrote $CFG"
}

__resolve_ndk(){
  : "${ANDROID_HOME:=$HOME/opt/android-sdk}"
  : "${ANDROID_SDK_ROOT:=$ANDROID_HOME}"
  if [ -n "${NDK_VERSION:-}" ] && [ -d "$ANDROID_HOME/ndk/$NDK_VERSION" ]; then
    export ANDROID_NDK_HOME="$ANDROID_HOME/ndk/$NDK_VERSION"
  fi
  if [ -z "${ANDROID_NDK_HOME:-}" ]; then
    __set_android_base >/dev/null 2>&1 || true
  fi
  local prebuilt_os="linux-aarch64"
  if [ -d "${ANDROID_NDK_HOME:-}/toolchains/llvm/prebuilt/$prebuilt_os" ]; then
    export TOOLCHAIN="$ANDROID_NDK_HOME/toolchains/llvm/prebuilt/$prebuilt_os"
    export NDK_LLVM_BIN="$TOOLCHAIN/bin"
    export NDK_SYSROOT="$TOOLCHAIN/sysroot"
  else
    unset TOOLCHAIN NDK_LLVM_BIN NDK_SYSROOT
  fi
  : "${ANDROID_API:=28}"
  export NDK_TRIPLE="aarch64-linux-android${ANDROID_API}"
}

__write_meson_cross(){
  mkdir -p "$HOME/.config/meson/cross"
  cat > "$HOME/.config/meson/cross/_current-ndk-cross.ini" <<EOF
[binaries]
c = '$NDK_LLVM_BIN/$NDK_TRIPLE-clang'
cpp = '$NDK_LLVM_BIN/$NDK_TRIPLE-clang++'
ar = '$NDK_LLVM_BIN/llvm-ar'
ranlib = '$NDK_LLVM_BIN/llvm-ranlib'
strip = '$NDK_LLVM_BIN/llvm-strip'
pkgconfig = '$PREFIX/bin/pkg-config'
[properties]
needs_exe_wrapper = true
c_args = ['--target=$NDK_TRIPLE','--sysroot=$NDK_SYSROOT','-D__ANDROID_API__=$ANDROID_API','-O2','-fPIC']
cpp_args = ['--target=$NDK_TRIPLE','--sysroot=$NDK_SYSROOT','-D__ANDROID_API__=$ANDROID_API','-O2','-fPIC','-stdlib=libc++','-isystem','$NDK_SYSROOT/usr/include/c++/v1']
c_link_args = ['--target=$NDK_TRIPLE','--sysroot=$NDK_SYSROOT']
cpp_link_args = ['--target=$NDK_TRIPLE','--sysroot=$NDK_SYSROOT']
pkg_config_libdir = ''
pkg_config_path = ''
[host_machine]
system = 'android'
cpu_family = 'aarch64'
cpu = 'armv8-a'
endian = 'little'
EOF

  cat > "$HOME/.config/meson/cross/_current-ndk-hybrid.ini" <<EOF
[binaries]
c = '$NDK_LLVM_BIN/$NDK_TRIPLE-clang'
cpp = '$NDK_LLVM_BIN/$NDK_TRIPLE-clang++'
ar = '$NDK_LLVM_BIN/llvm-ar'
ranlib = '$NDK_LLVM_BIN/llvm-ranlib'
strip = '$NDK_LLVM_BIN/llvm-strip'
pkgconfig = '$PREFIX/bin/pkg-config'
[properties]
needs_exe_wrapper = true
android_api = $ANDROID_API
c_args = ['--target=$NDK_TRIPLE','--sysroot=$NDK_SYSROOT','-D__ANDROID_API__=$ANDROID_API','-O2','-fPIC','-I$PREFIX/include']
cpp_args = ['--target=$NDK_TRIPLE','--sysroot=$NDK_SYSROOT','-D__ANDROID_API__=$ANDROID_API','-O2','-fPIC','-stdlib=libc++','-isystem','$NDK_SYSROOT/usr/include/c++/v1','-I$PREFIX/include']
c_link_args = ['--target=$NDK_TRIPLE','--sysroot=$NDK_SYSROOT','-L$PREFIX/lib']
cpp_link_args = ['--target=$NDK_TRIPLE','--sysroot=$NDK_SYSROOT','-L$PREFIX/lib']
pkg_config_libdir = '$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig'
[host_machine]
system = 'android'
cpu_family = 'aarch64'
cpu = 'armv8-a'
endian = 'little'
EOF
  echo "[compile-env] meson cross files updated for NDK=$ANDROID_NDK_HOME API=$ANDROID_API"
}

fizban_report(){
  cat <<EOF
[compile-env]
  PROFILE       : ${PROFILE:-<unset>}
  ANDROID_API   : ${ANDROID_API:-<unset>}
  ANDROID_HOME  : ${ANDROID_HOME:-<unset>}
  ANDROID_NDK_HOME : ${ANDROID_NDK_HOME:-<unset>}
  TOOLCHAIN     : ${TOOLCHAIN:-<unset>}
  NDK_LLVM_BIN  : ${NDK_LLVM_BIN:-<unset>}
  NDK_SYSROOT   : ${NDK_SYSROOT:-<unset>}
  NDK_TRIPLE    : ${NDK_TRIPLE:-<unset>}
  ENV_MODE      : ${ENV_MODE:-<unset>}
EOF
}

fizban_use(){
  local persist=0
  local sub="${1:-}"; shift || true
  case "$sub" in
    android)
      PROFILE=android
      while [ $# -gt 0 ]; do
        case "$1" in
          --ndk) NDK_VERSION="${2:?}"; shift 2;;
          --api) ANDROID_API="${2:?}"; shift 2;;
          --persist) persist=1; shift;;
          *) echo "usage: fizban_use android [--ndk VER] [--api N] [--persist]"; return 1;;
        esac
      done
      __resolve_ndk
      set_env_ndk_hybrid >/dev/null 2>&1 || true
      __write_meson_cross
      [ $persist -eq 1 ] && __cfg_save
      ;;
    mingw)
      PROFILE=mingw
      unset ANDROID_NDK_HOME TOOLCHAIN NDK_LLVM_BIN NDK_SYSROOT NDK_TRIPLE
      export TARGET="aarch64-w64-mingw32"
      export CC="$(command -v clang)"; export CXX="$(command -v clang++)"
      export AR="$(command -v llvm-ar)"; export RANLIB="$(command -v llvm-ranlib)"; export STRIP="$(command -v llvm-strip)"
      [ "${1:-}" = "--persist" ] && __cfg_save
      ;;
    *)
      echo "usage: fizban_use {android|mingw} [--ndk VER] [--api N] [--persist]"
      return 1;;
  esac
  fizban_report
}

fizban_load_persisted(){
  __cfg_load
  : "${PROFILE:=android}"
  if [ "$PROFILE" = "android" ]; then
    __resolve_ndk
    set_env_ndk_hybrid >/dev/null 2>&1 || true
    __write_meson_cross
  elif [ "$PROFILE" = "mingw" ]; then
    fizban_use mingw
  fi
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  case "${1:-}" in
    use) shift; fizban_use "$@";;
    report) fizban_report;;
    load) fizban_load_persisted;;
    *) echo "usage: $(basename "$0") {use|report|load} ..."; exit 1;;
  esac
fi
EOS
chmod +x "$HOME/bin/compile-env.sh"

